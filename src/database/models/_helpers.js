/**
 * Column definition helpers shared by every Sequelize model.
 *
 * Using these helpers instead of writing attribute objects by hand keeps the schema conventions identical across
 * all tables: UUID primary and foreign keys, NVARCHAR (Unicode) strings so names in any script are stored
 * correctly, NVARCHAR(MAX) for long text, JSON stored as text with safe parsing, and workflow status columns that
 * are validated against a fixed list of values.
 *
 * @author Kwasi Adabo Boakye
 */

import { DataTypes, Op } from 'sequelize';

export { DataTypes, Op };

/**
 * Primary key column: a UUID generated by the application.
 *
 * UUIDs are used instead of sequential integers so identifiers cannot be guessed or enumerated through the API.
 *
 * @returns {object} Sequelize attribute definition.
 */
export const pk = () => ({ type: DataTypes.UUID, defaultValue: DataTypes.UUIDV4, primaryKey: true });

/**
 * Foreign key column holding the UUID of a related row.
 *
 * @param {boolean} [allowNull=true] Whether the relationship is optional.
 * @returns {object} Sequelize attribute definition.
 */
export const fk = (allowNull = true) => ({ type: DataTypes.UUID, allowNull });

/**
 * Optional Unicode string column (NVARCHAR).
 *
 * @param {number} [len=255] Maximum length in characters.
 * @param {object} [opts={}] Extra attribute options, such as a default value or validation.
 * @returns {object} Sequelize attribute definition.
 */
export const str = (len = 255, opts = {}) => ({ type: DataTypes.STRING(len), allowNull: true, ...opts });

/**
 * Required Unicode string column (NVARCHAR, NOT NULL).
 *
 * @param {number} [len=255] Maximum length in characters.
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const req = (len = 255, opts = {}) => ({ type: DataTypes.STRING(len), allowNull: false, ...opts });

/**
 * Optional long text column (NVARCHAR(MAX)), used for descriptive fields such as scope and content notes.
 *
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const text = (opts = {}) => ({ type: DataTypes.TEXT, allowNull: true, ...opts });

/**
 * Required boolean column (BIT) with a default value.
 *
 * @param {boolean} [def=false] Default value for new rows.
 * @returns {object} Sequelize attribute definition.
 */
export const bool = (def = false) => ({ type: DataTypes.BOOLEAN, allowNull: false, defaultValue: def });

/**
 * Integer column. The column is nullable only when no default is given, so counters with a default of 0 can
 * never be NULL.
 *
 * @param {number|null} [def=null] Default value; null makes the column optional.
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const int = (def = null, opts = {}) => ({
  type: DataTypes.INTEGER,
  allowNull: def === null,
  defaultValue: def,
  ...opts,
});

/**
 * Optional 64-bit integer column, used for file sizes in bytes.
 *
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const big = (opts = {}) => ({ type: DataTypes.BIGINT, allowNull: true, ...opts });

/**
 * Optional date-and-time column (DATETIME2), always stored in UTC.
 *
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const date = (opts = {}) => ({ type: DataTypes.DATE, allowNull: true, ...opts });

/**
 * Optional calendar date column without a time (DATE), used for archival dates and due dates.
 *
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const dateOnly = (opts = {}) => ({ type: DataTypes.DATEONLY, allowNull: true, ...opts });

/**
 * Optional fixed-precision decimal column, used for measurements and fees.
 *
 * @param {number} [p=12] Total number of digits.
 * @param {number} [s=2] Digits after the decimal point.
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition.
 */
export const dec = (p = 12, s = 2, opts = {}) => ({ type: DataTypes.DECIMAL(p, s), allowNull: true, ...opts });

/**
 * Required workflow status column restricted to a fixed list of values.
 *
 * @param {string[]} values The allowed states, for example ['draft', 'submitted', 'approved'].
 * @param {string} [def] Initial state; defaults to the first value in the list.
 * @returns {object} Sequelize attribute definition with an \`isIn\` validator.
 */
export const status = (values, def) => ({
  type: DataTypes.STRING(40),
  allowNull: false,
  defaultValue: def ?? values[0],
  validate: { isIn: [values] },
});

/**
 * Optional string column restricted to a fixed list of values (an enumeration stored as text).
 *
 * @param {string[]} values The allowed values.
 * @param {object} [opts={}] Extra attribute options.
 * @returns {object} Sequelize attribute definition with an \`isIn\` validator.
 */
export const enumStr = (values, opts = {}) => ({
  type: DataTypes.STRING(40),
  allowNull: true,
  validate: { isIn: [values] },
  ...opts,
});

/**
 * Column that stores a JavaScript value as JSON text and converts it transparently on read and write.
 *
 * SQL Server has no native JSON column type, so the value is kept in NVARCHAR(MAX). Malformed stored text is
 * returned as the default instead of throwing, so one damaged value cannot break a whole list page.
 *
 * @param {string} field Name of the attribute; needed by the getter and setter to reach the raw value.
 * @param {*} [def=null] Value returned when the column is empty or cannot be parsed.
 * @returns {object} Sequelize attribute definition with a getter and setter.
 */
export function json(field, def = null) {
  return {
    type: DataTypes.TEXT,
    allowNull: true,
    /**
     * Parses the stored JSON text, returning the default for empty or malformed values.
     *
     * @returns {*} The parsed value.
     */
    get() {
      const raw = this.getDataValue(field);
      if (raw === null || raw === undefined || raw === '') return def;
      try {
        return JSON.parse(raw);
      } catch {
        return def;
      }
    },
    /**
     * Serialises the value to JSON text; null and undefined are stored as NULL.
     *
     * @param {*} value The value to store.
     */
    set(value) {
      this.setDataValue(field, value === null || value === undefined ? null : JSON.stringify(value));
    },
  };
}

/**
 * Index definition that enforces uniqueness only among rows where the column has a value.
 *
 * A plain unique index in SQL Server allows only one NULL, which would prevent more than one row from leaving an
 * optional identifier (such as a barcode) empty. The filtered index ignores NULL values.
 *
 * @param {string} field Column that must be unique when set.
 * @returns {object} Sequelize index definition.
 */
export const uniqueWhenSet = (field) => ({ unique: true, fields: [field], where: { [field]: { [Op.ne]: null } } });
